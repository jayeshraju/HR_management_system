import { Router } from 'express';
import { authRoutes } from './authRoutes.js';
import { requireAuth, requireRole } from '../middleware/auth.js';
import { employeeRoutes } from './employeeRoutes.js';
import { hrAttendanceRoutes } from './hrAttendanceRoutes.js';
import { hrLeaveRoutes } from './hrLeaveRoutes.js';
import { hrRoutes } from './hrRoutes.js';
import { analyticsRoutes } from './analyticsRoutes.js';
import { assistantRoutes } from './assistantRoutes.js';
import { notificationRoutes } from './notificationRoutes.js';
import { auditRoutes } from './auditRoutes.js';
import { reportRoutes } from './reportRoutes.js';
import { demoRoutes } from './demoRoutes.js';
export const apiRoutes = Router();
apiRoutes.get('/health', (_req, res) => res.json({ status: 'ok', service: 'dayflow-api' }));
apiRoutes.use('/auth', authRoutes);
apiRoutes.use('/employee', employeeRoutes);
apiRoutes.use('/hr/attendance', hrAttendanceRoutes);
apiRoutes.use('/hr/leave', hrLeaveRoutes);
apiRoutes.use('/hr', hrRoutes);
apiRoutes.use('/analytics', analyticsRoutes);
apiRoutes.use('/assistant', assistantRoutes);
apiRoutes.use('/notifications', notificationRoutes);
apiRoutes.use('/audit-logs', auditRoutes);
apiRoutes.use('/reports', reportRoutes);
apiRoutes.use('/demo', demoRoutes);
apiRoutes.get('/hr/dashboard', requireAuth, requireRole('hr'), (_req, res) => res.json({ message: 'HR foundation route ready' }));
